# Count chars in each section: 汉字 + 标点 (exclude ASCII letters / digits / spaces / control / markdown special)
def cn_count(text):
    # 统计汉字 + 中文标点 + 必要的中文符号；不含英文字母数字、空格、Markdown 标点
    n = 0
    for ch in text:
        if ch.isspace():
            continue
        # 排除 ASCII 字母数字
        if '0' <= ch <= '9' or 'A' <= ch <= 'Z' or 'a' <= ch <= 'z':
            continue
        # 排除常见 ASCII 标点 (Markdown / 拉丁标点)
        if ch in ".,;:!?-_=+()[]{}<>\\/|@#$%^&*~`'\"":
            continue
        # 其余按"含"处理（汉字 + 中文标点 + 单位符号 + 中英混排里的非英文部分）
        n += 1
    return n

# Better: count 汉字 (CJK Unified Ideographs) + 中文标点 (CJK Symbols and Punctuation, Fullwidth)
def strict_cn_count(text):
    n = 0
    for ch in text:
        cp = ord(ch)
        # 汉字范围
        if 0x4E00 <= cp <= 0x9FFF or 0x3400 <= cp <= 0x4DBF:
            n += 1
            continue
        # 全角标点 / 字母 / 数字
        if 0xFF00 <= cp <= 0xFFEF:
            n += 1
            continue
        # CJK 符号
        if 0x3000 <= cp <= 0x303F:
            n += 1
            continue
    return n

