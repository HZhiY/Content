BASE_DATE = "2026-06-09"


def parse_reads(s: str) -> int:
    s = s.strip()
    if s.endswith("万"):
        return int(float(s[:-1]) * 10000)
    return int(s.replace(",", ""))


def normalize_date(d: str) -> str:
    if d == "2小时前":
        return f"{BASE_DATE} ({d})"
    if d == "20小时前":
        return f"2026-06-08 ({d})"
    if d == "前天22:20":
        return f"2026-06-07 22:20 ({d})"
    if d == "前天14:23":
        return f"2026-06-07 14:23 ({d})"
    if d == "前天12:08":
        return f"2026-06-07 12:08 ({d})"
    if d.endswith("天前") and d[0].isdigit():
        days = int(d.replace("天前", ""))
        from datetime import datetime, timedelta
        dt = datetime.strptime(BASE_DATE, "%Y-%m-%d") - timedelta(days=days)
        return f"{dt.strftime('%Y-%m-%d')} ({d})"
    if d.startswith("04-") or d.startswith("05-") or d.startswith("03-"):
        return f"2026-{d}"
    return d


