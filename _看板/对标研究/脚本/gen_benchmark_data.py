RELATIVE_DATES = {
    "3天前": "2026-06-06",
    "4天前": "2026-06-05",
    "5天前": "2026-06-04",
    "6天前": "2026-06-03",
    "7天前": "2026-06-02",
    "8天前": "2026-06-01",
}


def parse_reads(s: str) -> int:
    s = s.strip()
    if s.endswith("万"):
        return int(float(s[:-1]) * 10000)
    return int(s.replace(",", ""))


def normalize_date(d: str) -> str:
    if d in RELATIVE_DATES:
        return f"{RELATIVE_DATES[d]}（{d}）"
    if d.startswith("05-") or d.startswith("04-"):
        return f"2026-{d}"
    return d


